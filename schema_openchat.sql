-- みんなの部屋（LINEオープンチャット）のお名前
-- 2026-08 Photelierサロン用
--
-- なぜ要るか：
-- オープンチャットは匿名で参加できる仕組みなので、参加者一覧には
-- 「その部屋用の表示名」しか出ない。本名でもメールアドレスでもない。
-- そのままだと、退会された方がどの人なのか分からず、部屋に残り続けてしまう。
--
-- そこで「みんなの部屋で使うお名前」を先に教えていただき、ここに保存する。
-- 保存して初めて参加コードが表示される（会員サイトの中だけに出る）。
-- これで「お申し込みの方」と「部屋の表示名」が1対1でつながる。
--
-- 月に1回、退会された方をこの名簿で探して、部屋から外していただく。

alter table members
  add column if not exists openchat_name text;

comment on column members.openchat_name is
  'みんなの部屋（LINEオープンチャット）で使っている表示名。空＝まだ参加していない方。';
